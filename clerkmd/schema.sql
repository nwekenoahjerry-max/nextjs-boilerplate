CREATE TABLE IF NOT EXISTS users(
  id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT UNIQUE NOT NULL, name TEXT, school TEXT, level TEXT,
  pw TEXT NOT NULL, salt TEXT NOT NULL, plan TEXT DEFAULT 'free', pro_until INTEGER DEFAULT 0,
  settings TEXT DEFAULT '{}', xp INTEGER DEFAULT 0, streak INTEGER DEFAULT 0, last_day TEXT, created INTEGER);
CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY, uid INTEGER, exp INTEGER);
CREATE TABLE IF NOT EXISTS attempts(id INTEGER PRIMARY KEY AUTOINCREMENT, uid INTEGER, unit TEXT, case_id TEXT, score INTEGER, at INTEGER);
CREATE TABLE IF NOT EXISTS payments(ref TEXT PRIMARY KEY, uid INTEGER, amount INTEGER, plan TEXT, status TEXT, at INTEGER);
CREATE TABLE IF NOT EXISTS resets(tok TEXT PRIMARY KEY, uid INTEGER, exp INTEGER);
CREATE TABLE IF NOT EXISTS google_accounts(
  sub TEXT PRIMARY KEY, uid INTEGER NOT NULL UNIQUE, created INTEGER NOT NULL,
  FOREIGN KEY(uid) REFERENCES users(id)
);